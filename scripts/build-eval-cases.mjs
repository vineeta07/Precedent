// Turns tests/eval/conflicts.jsonl (the source of truth) into a TS module so the
// same cases can run offline (npm run eval) and inside the app against Forge LLMs.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lines = readFileSync(join(root, 'tests/eval/conflicts.jsonl'), 'utf8').split('\n').filter((l) => l.trim());
const cases = lines.map((l, i) => {
  try {
    return JSON.parse(l);
  } catch (e) {
    throw new Error(`conflicts.jsonl line ${i + 1} is not valid JSON: ${e.message}`);
  }
});
const out =
  '// GENERATED by scripts/build-eval-cases.mjs from tests/eval/conflicts.jsonl. Do not edit.\n' +
  "import type { EvalCase } from './types';\n\n" +
  `export const EVAL_CASES: EvalCase[] = ${JSON.stringify(cases, null, 2)};\n`;
writeFileSync(join(root, 'src/ai/eval/cases.ts'), out);
console.log(`wrote ${cases.length} eval cases`);
